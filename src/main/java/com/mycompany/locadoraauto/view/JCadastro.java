    private void jButtonTipoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonTipoActionPerformed
        int tipo = jComboTipo.getSelectedIndex();
        jComboTipo.setEditable(false);
        jComboTipo.setEnabled(false);
        jButtonTipo.setEnabled(false);
        switch (tipo) {
            case 1 -> {
                jPanel2.removeAll();
                jPanel2.add(jPanelAuto);
                jPanel2.repaint();
                jPanel2.revalidate();
            }
            case 3 -> {
                jPanel2.removeAll();
                jPanel2.add(jPanelLocador);
                jPanel2.repaint();
                jPanel2.revalidate();
            }
            case 4 -> {
                jPanel2.removeAll();
                jPanel2.add(jPanelVendedor);
                jPanel2.repaint();
                jPanel2.revalidate();
            }
            case 5 -> {
                jPanel2.removeAll();
                jPanel2.add(jPanelMontadora);
                jPanel2.repaint();
                jPanel2.revalidate();
            }
            case 2 -> {
                jPanel2.removeAll();
                jPanel2.add(jPanelAlugador);
                jPanel2.repaint();
                jPanel2.revalidate();
            }
            default -> {
                jPanel2.removeAll();
                jPanel2.add(jPanelVazio);
                jPanel2.repaint();
                jPanel2.revalidate();
            }
        }
        jComboTipo.setEnabled(false);
    }//GEN-LAST:event_jButtonTipoActionPerformed

